def git_ignored(directory, paths):
    'The subset of `paths` (absolute, under `directory`) that git ignores or excludes\n    there. Empty when git cannot answer, so a failure hides nothing.'
    rels = [os.path.relpath(p, directory) for p in paths if p != directory]
    if not rels:
        return set()
    try:
        p = subprocess.run(["git", "-C", directory, "check-ignore", "-z", "--stdin"],
                           input="\0".join(rels) + "\0", capture_output=True, text=True,
                           timeout=30)
    except (OSError, subprocess.SubprocessError):
        return set()
    return {os.path.join(directory, r) for r in p.stdout.split("\0") if r}


def report_stray_harness_dirs(directory):
    'A harness dir anywhere but the repo root is served in preference to the projected one.'
    found = []
    worktrees = {os.path.join(directory, scope, "worktrees") for scope in (hp.AGENTS_DIRNAME, hp.CLAUDE_DIRNAME)}
    for dirpath, dirnames, _filenames in os.walk(directory):
        keep = []
        for name in sorted(dirnames):
            full = os.path.join(dirpath, name)
            if name in PRUNE_DIR_NAMES or full in worktrees:
                continue
            keep.append(name)
            if name in (hp.CLAUDE_DIRNAME, hp.AGENTS_DIRNAME):
                found.append(full)
        dirnames[:] = keep
    exclude = {hp.project_claude_dir(directory), hp.project_agents_dir(directory)}
    found = [d for d in found if d not in exclude]
    ignored = git_ignored(directory, sorted({os.path.dirname(d) for d in found}))
    n = 0
    for d in found:
        parent = os.path.dirname(d)
        
        
        if parent in ignored or os.path.lexists(os.path.join(parent, ".git")):
            continue
        try:
            entries = [e for e in os.listdir(d) if e != "tmp"]
        except OSError:
            entries = []
        if not entries:
            continue
        n += 1
        rel = d[len(directory) + 1:] if d.startswith(directory + os.sep) else d
        print("  ⚠ STRAY harness directory outside the repo root — the harness serves it in "
              "preference to the projection whenever work touches its subtree, and it is in no store scope, "
              "so no audit can see it: %s" % rel)
    return n == 0


def report_shadowed(directory):
    'A store entity that shadows a file the repo already tracks. Reported, never refused.'
    proc = subprocess.run(["git", "-C", directory, "rev-parse", "--is-inside-work-tree"], capture_output=True)
    if proc.returncode != 0:
        return
    tracked_proc = subprocess.run(["git", "-C", directory, "ls-files"], capture_output=True, text=True)
    if tracked_proc.returncode != 0:
        return
    tracked = tracked_proc.stdout
    if not tracked.strip():
        return
    tracked_lines = tracked.splitlines()
    shown = False
    for sub in ("hooks", "scripts"):
        d = os.path.join(directory, ".agents", sub)
        if not os.path.isdir(d):
            continue
        for base in sorted(os.listdir(d)):
            full = os.path.join(d, base)
            if not os.path.isfile(full):
                continue
            if base.endswith(".meta.toml") or base.endswith(".meta.json"):
                continue
            regex = re.compile(r'(^|/)' + re.escape(base) + r'$')
            hits = [t for t in tracked_lines if regex.search(t)]
            if not hits:
                continue
            if not shown:
                print("  ⚠ store entities that shadow a file this repo already tracks:")
                shown = True
            print("      %s — the repo also tracks: %s" % (base, " ".join(hits)))
    if shown:
        print("      One of the two is the real one, and they will drift. If the repo's copy")
        print("      is canonical, delete the store entity; if the store's is, delete the")
        print("      repo's and stop tracking it.")


