SCOPE_EVIDENCE_LIMIT = 8
SCOPE_ROOTS = ("projects", "workspaces")


class ScopeFetchRefused(Exception):
    'A reason safe to print: never carries the token or a response body.'


def scope_key_is_safe(key):
    'No empty, `.` or `..` segment, not absolute, no trailing slash; a projects/ or\n    workspaces/ key also needs a file below its scope directory.'
    if not isinstance(key, str) or not key or "\x00" in key or "\\" in key or key.startswith("/"):
        return False
    parts = key.split("/")
    if any(part in ("", ".", "..") for part in parts):
        return False
    return len(parts) >= 3 or parts[0] not in SCOPE_ROOTS


def scope_repo_evidence(directory):
    '(repo_root, marker id or None, remote urls) for the repo at directory, or None.'
    ev = store_mcp.repo_evidence(directory)
    if not ev["marker_id"] and not ev["remotes"]:
        return None
    return ev["cwd"], ev["marker_id"], ev["remotes"]


def scope_write_atomic(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".pmfetch.", dir=os.path.dirname(path))
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.remove(tmp)
        except OSError:
            pass
        raise


def scope_remove_empty_dirs(store, path):
    'Remove emptied parents of path, up to (not including) the store root.'
    parent = os.path.dirname(path)
    while parent != store and parent.startswith(store + os.sep):
        try:
            os.rmdir(parent)
        except OSError:
            return
        parent = os.path.dirname(parent)


def scope_drop_files(store, keys, digests, protected):
    'Delete recorded files whose bytes still equal what was written and no live record lists.'
    for key in keys:
        if key in protected or not scope_key_is_safe(key) or key.split("/")[0] not in SCOPE_ROOTS:
            continue
        path = os.path.join(store, key)
        if not os.path.realpath(os.path.dirname(path)).startswith(os.path.realpath(store) + os.sep):
            continue  
        try:
            with open(path, "rb") as fh:
                current = hashlib.sha256(fh.read()).hexdigest()
        except OSError:
            continue
        if digests.get(key) != current:
            continue
        try:
            os.remove(path)
        except OSError:
            continue  
        scope_remove_empty_dirs(store, path)


def scope_read_record(path):
    '(record, digests) or None for a missing or malformed record.'
    try:
        with open(path, encoding="utf-8") as fh:
            record = json.load(fh)
    except (OSError, ValueError):
        return None
    if not isinstance(record, dict) or not isinstance(record.get("keys"), list):
        return None
    digests = record.get("digests") if isinstance(record.get("digests"), dict) else {}
    return record, digests


def scope_request(env, project, remotes):
    "The response's projects/ and workspaces/ keys; refuses the whole response on any unsafe key."
    try:
        bundle = store_mcp.call("get_materialized",
                                {"project": [project] if project else [], "remote": list(remotes)},
                                env=env)
    except (store_mcp.ToolError, store_mcp.StoreUnreachable) as exc:
        raise ScopeFetchRefused(str(exc))
    if not isinstance(bundle, dict) or not all(isinstance(k, str) and isinstance(v, str)
                                               for k, v in bundle.items()):
        raise ScopeFetchRefused("response is not a string map")
    if not all(scope_key_is_safe(k) for k in bundle):
        raise ScopeFetchRefused("response has an unsafe key")
    return {k: v for k, v in bundle.items() if k.split("/")[0] in SCOPE_ROOTS}


def scope_first_toml_value(text, key):
    m = re.search(r'^' + re.escape(key) + r' *= *"(.*)"', text, re.M)
    return m.group(1) if m else ""


def relay_configured():
    'A relay machine: host and token are known. A store with neither is read as it stands.'
    env = store_mcp.relay_env()
    return bool(env["AGENT_CONTEXT_HOST"] and env["AGENT_CONTEXT_TOKEN"])


def store_is_checkout(store):
    return os.path.exists(os.path.join(store, ".git")) or os.path.isdir(os.path.join(store, "server"))


def scope_fetch(directory, scope_tmp):
    "Fetch the cwd project's projects/ and workspaces/ keys into a per-run temp tree and return\n    its path, or None when there is nothing to ask. The path is appended to scope_tmp first, so\n    the caller deletes it even when this raises."
    env = store_mcp.relay_env()
    if not env["AGENT_CONTEXT_HOST"] or not env["AGENT_CONTEXT_TOKEN"]:
        return None
    if not os.path.isdir(directory):
        return None
    evidence = scope_repo_evidence(directory)
    if evidence is None:
        return None
    _root, marker, urls = evidence
    bundle = scope_request(env, marker, urls[:SCOPE_EVIDENCE_LIMIT - (1 if marker else 0)])

    created = []
    temp_root = os.environ.get("TMPDIR")
    if not temp_root:
        agents_tmp = os.path.join(directory, ".agents", "tmp")
        for path in (os.path.dirname(agents_tmp), agents_tmp):
            if not os.path.isdir(path):
                os.makedirs(path, exist_ok=True)
                created.append(path)
        temp_root = agents_tmp
    tree = tempfile.mkdtemp(prefix="pmscope.", dir=temp_root)
    scope_tmp.append((tree, tuple(created)))
    real_tree = os.path.realpath(tree)
    for key in bundle:
        if not os.path.realpath(os.path.dirname(os.path.join(tree, key))).startswith(real_tree + os.sep):
            raise ScopeFetchRefused("response has an unsafe key")
    for key, text in sorted(bundle.items()):
        scope_write_atomic(os.path.join(tree, key), text.encode("utf-8"))
    return tree


def scope_retire_legacy(store):
    "Delete what an older version wrote under the store's projects/ and workspaces/: each file\n    a record lists whose bytes still equal the digest it holds, then the record itself."
    record_dir = os.path.join(HOME, ".cache", "agent-context", "project-scope")
    try:
        names = sorted(os.listdir(record_dir))
    except OSError:
        return
    for name in names:
        if not name.endswith(".json"):
            continue
        path = os.path.join(record_dir, name)
        got = scope_read_record(path)
        if got:
            scope_drop_files(store, [k for k in got[0]["keys"] if isinstance(k, str)], got[1], set())
        try:
            os.remove(path)
        except OSError:
            pass
    try:
        os.rmdir(record_dir)
    except OSError:
        pass


def scope_sweep_ds_store(store):
    "Remove dirs under the store's projects/ and workspaces/ that hold nothing but Finder's\n    .DS_Store files (what a retire leaves on macOS), the .DS_Store files with them. Bottom-up, so a\n    dir emptied by its children's removal goes too. The store root, a symlinked dir and a\n    symlinked .DS_Store are never touched, and a dir with any other entry keeps its .DS_Store."
    for root_name in SCOPE_ROOTS:
        root = os.path.join(store, root_name)
        if os.path.islink(root) or not os.path.isdir(root):
            continue
        for dirpath, _dirnames, _filenames in os.walk(root, topdown=False, followlinks=False):
            if os.path.islink(dirpath):
                continue
            try:
                entries = os.listdir(dirpath)
            except OSError:
                continue
            
            
            if not entries or any(e != ".DS_Store" or os.path.islink(os.path.join(dirpath, e))
                                  or not os.path.isfile(os.path.join(dirpath, e)) for e in entries):
                continue
            for e in entries:
                try:
                    os.remove(os.path.join(dirpath, e))
                except OSError:
                    break
            try:
                os.rmdir(dirpath)
            except OSError:
                pass




def parse_args(argv):
    check = False
    directory = None
    for a in argv:
        if a == "--check":
            check = True
        elif a.startswith("-"):
            print("project-materialize: unknown flag %s" % a, file=sys.stderr)
            sys.exit(2)
        else:
            directory = a
    return check, directory


