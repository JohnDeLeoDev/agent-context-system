def assert_git_exclude(directory, project):
    'Nothing agent-related is ever committed into a project repo. Excluded via .git/info/exclude.'
    git_dir = os.path.join(directory, ".git")
    if not os.path.isdir(git_dir):
        return
    excl = os.path.join(git_dir, "info", "exclude")
    try:
        os.makedirs(os.path.dirname(excl), exist_ok=True)
    except OSError:
        pass
    existing_lines = set()
    existing_text = ""
    if os.path.isfile(excl):
        try:
            with open(excl, encoding="utf-8", errors="replace") as fh:
                existing_text = fh.read()
        except OSError:
            existing_text = ""
        existing_lines = set(existing_text.splitlines())
    if "agent-context generated (never commit)" not in existing_text:
        try:
            with open(excl, "a", encoding="utf-8") as fh:
                fh.write("\n# --- agent-context generated (never commit) ---------------------------\n")
                fh.write("# Written by project-materialize.py; regenerated every session, per machine.\n")
            print("project-materialize[%s]: added agent-generated files to .git/info/exclude" % project)
        except OSError:
            pass
    for pat in ("/AGENTS*.md", "/CLAUDE*.md*", "/buildServer.json", "/.compile",
                ".agents/", hp.CLAUDE_DIRNAME + "/", ".opencode/", "/opencode.json",
                "/.claudeignore", "/.cgcignore", ".orca/", "/mcp.json"):
        if pat not in existing_lines:
            try:
                with open(excl, "a", encoding="utf-8") as fh:
                    fh.write(pat + "\n")
                existing_lines.add(pat)
            except OSError:
                pass
    for f in ("AGENTS.md", "CLAUDE.md", "buildServer.json", ".compile", ".agents", hp.CLAUDE_DIRNAME):
        proc = subprocess.run(["git", "-C", directory, "ls-files", "--", f], capture_output=True, text=True)
        tracked = proc.stdout
        if not tracked.strip():
            continue
        print("  ⚠ %s is TRACKED in git — agent-generated files must not be committed." % f,
              file=sys.stderr)
        for line in tracked.splitlines():
            print("        %s" % line, file=sys.stderr)
        print("    Untrack the paths listed above:  git rm --cached -- <path>…   (then commit)",
              file=sys.stderr)




