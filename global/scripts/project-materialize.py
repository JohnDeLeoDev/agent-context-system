def read_toml_all(path, key):
    'Every value of `key = "..."` in path, newline-joined (sed -n \'s/^key.../\\1/p\', no head).'
    if not os.path.isfile(path):
        return ""
    pattern = re.compile(r'^' + re.escape(key) + r' *= *"(.*)"')
    found = []
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            for line in fh:
                m = pattern.match(line.rstrip("\n"))
                if m:
                    found.append(m.group(1))
    except OSError:
        return ""
    return "\n".join(found)


def read_toml_first(path, key):
    all_ = read_toml_all(path, key)
    return all_.splitlines()[0] if all_ else ""




def url_identifies_repo(u, r):
    'Does a remote url identify this repo, compared on a PATH BOUNDARY (never a bare substring).'
    if u.endswith(".git"):
        u = u[:-4]
    if r.endswith(".git"):
        r = r[:-4]
    if not r:
        return False
    if u == r:
        return True
    if u.endswith("/" + r):
        return True
    if u.endswith(":" + r):
        return True
    return False


def resolve_project(directory, store):
    base = os.path.basename(directory)
    if os.path.isfile(os.path.join(store, "projects", base, "project.toml")):
        return base
    proc = subprocess.run(["git", "-C", directory, "config", "--get-all", "remote.origin.url"],
                          capture_output=True, text=True)
    urls = proc.stdout if proc.returncode == 0 else ""
    if not urls.strip():
        return None
    matches = []
    for pt in sorted(glob.glob(os.path.join(store, "projects", "*", "project.toml"))):
        cr = read_toml_all(pt, "canonical_remote")
        if not cr:
            continue
        repo = cr.split(":", 1)[1] if ":" in cr else cr
        name = os.path.basename(os.path.dirname(pt))
        for url in urls.splitlines():
            if not url:
                continue
            if url_identifies_repo(url, repo):
                if name not in matches:
                    matches.append(name)
                break
    if not matches:
        return None
    if len(matches) > 1:
        print("project-materialize: REFUSING - %s matches more than one store project (%s). "
              "Fix the duplicate canonical_remote." % (directory, " ".join(matches)), file=sys.stderr)
        return None
    return matches[0]


def is_git_repo(directory):
    if os.path.isdir(os.path.join(directory, ".git")):
        return True
    proc = subprocess.run(["git", "-C", directory, "rev-parse", "--git-dir"], capture_output=True)
    return proc.returncode == 0


def logical_pwd(path):
    '`cd "$path" 2>/dev/null && pwd || echo "$path"` -- logical, symlink-preserving pwd.'
    proc = subprocess.run(["bash", "-c", 'cd "$1" 2>/dev/null && pwd || echo "$1"', "_", path],
                          capture_output=True, text=True)
    return proc.stdout.rstrip("\n")




def scrub(path):
    'Drop store-only artifacts (*.meta.toml, *.meta.json, .DS_Store, __pycache__) from a projection.'
    if not os.path.isdir(path):
        return
    for dirpath, dirnames, filenames in os.walk(path, topdown=False):
        for fname in filenames:
            if fname.endswith(".meta.toml") or fname.endswith(".meta.json") or fname == ".DS_Store":
                try:
                    os.remove(os.path.join(dirpath, fname))
                except OSError:
                    pass
        for dname in dirnames:
            if dname == "__pycache__":
                shutil.rmtree(os.path.join(dirpath, dname), ignore_errors=True)


def strip_fm(root):
    frontmatter_strip.strip_frontmatter_tree([root])


def make_executable(path, skip_md=False):
    if not os.path.isdir(path):
        return
    for dirpath, _dirnames, filenames in os.walk(path):
        for fname in filenames:
            if skip_md and fname.endswith(".md"):
                continue
            full = os.path.join(dirpath, fname)
            try:
                st = os.stat(full)
                os.chmod(full, st.st_mode | 0o111)
            except OSError:
                pass


def stamp_generated(root):
    "Scripts and hooks only: a .md entity's first line is load-bearing frontmatter,\n    and prepending to it would break how every harness parses a skill."
    if not os.path.isdir(root):
        return
    for dirpath, _dirnames, filenames in os.walk(root):
        for fname in filenames:
            if fname.endswith(".md"):
                continue
            f = os.path.join(dirpath, fname)
            try:
                with open(f, "rb") as fh:
                    data = fh.read()
            except OSError:
                continue
            if GENERATED_MARKER_TEXT.encode("utf-8") in data:
                continue
            try:
                text = data.decode("utf-8")
            except UnicodeDecodeError:
                continue
            lines = text.split("\n")
            first = lines[0] if lines else ""
            banner = ("# GENERATED FILE — the canonical copy lives in the agent-context store.\n"
                      "# Edit it there (upsert_script / upsert_hook / edit_body), not here: this copy is\n"
                      "# overwritten at every SessionStart and after every store write, and an edit made\n"
                      "# here disappears with nothing announcing it (audit policy).\n")
            if first.startswith("#!"):
                new_text = first + "\n" + banner + "\n".join(lines[1:])
            else:
                new_text = banner + text
            tmp = f + ".gen"
            with open(tmp, "w", encoding="utf-8") as fh:
                fh.write(new_text)
            os.replace(tmp, f)


def build_into(stage, sub, rel, kind, base):
    'Build one target subtree from a store entity dir into $STAGE (mirrors .agents layout).'
    src = os.path.join(base, sub)
    dst = os.path.join(stage, rel)
    if not os.path.isdir(src):
        return
    os.makedirs(dst, exist_ok=True)
    shutil.copytree(src, dst, dirs_exist_ok=True, copy_function=shutil.copy2)
    scrub(dst)
    if kind == "content":
        strip_fm(dst)
    else:
        stamp_generated(dst)
        make_executable(dst)




def files_differ(a, b):
    '`diff -q` semantics: missing destination counts as differing.'
    if not os.path.isfile(b):
        return True
    try:
        with open(a, "rb") as fa, open(b, "rb") as fb:
            return fa.read() != fb.read()
    except OSError:
        return True


def walk_files(root):
    result = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames.sort()
        for fname in sorted(filenames):
            result.append(os.path.join(dirpath, fname))
    return result


def is_partial(rel):
    return rel in PARTIAL


def global_twin(rel, r):
    'Does a disk-only path under an owned subtree correspond to a GLOBAL store entity?'
    d = GLOBAL_TWIN_DIR.get(rel)
    if d is None:
        return False
    return os.path.exists(os.path.join(HOME, ".agent-context", "global", d, r))


def is_vendored_skill(live, rel, r):
    'A skill that ships its own references/ corpus came from upstream and belongs on disk.'
    if rel != "claude/skills":
        return False
    skill = r.split("/", 1)[0]
    if skill == r:
        return False
    return os.path.isdir(os.path.join(live, skill, "references"))


def sha256_of(path):
    try:
        h = hashlib.sha256()
        with open(path, "rb") as fh:
            for chunk in iter(lambda: fh.read(65536), b""):
                h.update(chunk)
        return h.hexdigest()
    except OSError:
        return ""


def manifest_sha(manifest, key):
    if not os.path.isfile(manifest):
        return ""
    try:
        with open(manifest, encoding="utf-8", errors="replace") as fh:
            for line in fh:
                parts = line.split()
                if len(parts) >= 2 and parts[1] == key:
                    return parts[0]
    except OSError:
        pass
    return ""


def classify(stage, ag):
    'Store files to add/update vs disk-only files to preserve, plus retirement candidates.\n\n    A disk-only file under an owned subtree is retired (deleted on apply, rescued first)\n    only when the manifest says materialize wrote it and its sha256 still matches: nobody\n    edited it since, so a store rename/removal is the only way it got here. A file with no\n    manifest entry, or whose sha no longer matches, is always kept and reported as disk-only,\n    exactly as before this existed.'
    updates = 0
    extras = 0
    shadows = 0
    retiring = 0
    extra_list = []
    shadow_list = []
    replaced_list = []
    rescue_list = []
    retire_list = []
    manifest = os.path.join(ag, "tmp", ".materialize-manifest")
    for rel in OWNED:
        staged = os.path.join(stage, rel)
        live = os.path.join(ag, rel)
        if os.path.isdir(staged):
            for f in walk_files(staged):
                r = os.path.relpath(f, staged)
                live_f = os.path.join(live, r)
                if files_differ(f, live_f):
                    updates += 1
                    if os.path.exists(live_f):
                        replaced_list.append(".agents/%s/%s" % (rel, r))
                        recorded = manifest_sha(manifest, "%s/%s" % (rel, r))
                        if recorded:
                            if sha256_of(live_f) != recorded:
                                rescue_list.append("%s/%s" % (rel, r))
                        elif os.path.getmtime(live_f) > os.path.getmtime(f):
                            rescue_list.append("%s/%s" % (rel, r))
        if not os.path.isdir(live):
            continue
        if is_partial(rel):
            continue
        for f in walk_files(live):
            r = os.path.relpath(f, live)
            if r.endswith(".DS_Store") or r.endswith(".meta.toml"):
                continue
            if is_vendored_skill(live, rel, r):
                continue
            if not os.path.exists(os.path.join(staged, r)):
                if global_twin(rel, r):
                    shadows += 1
                    shadow_list.append(".agents/%s/%s" % (rel, r))
                else:
                    recorded = manifest_sha(manifest, "%s/%s" % (rel, r))
                    if recorded and sha256_of(f) == recorded:
                        retiring += 1
                        retire_list.append("%s/%s" % (rel, r))
                    else:
                        extras += 1
                        extra_list.append(".agents/%s/%s" % (rel, r))
    return {
        "updates": updates, "extras": extras, "shadows": shadows, "retiring": retiring,
        "extra_list": extra_list, "shadow_list": shadow_list,
        "replaced_list": replaced_list, "rescue_list": rescue_list, "retire_list": retire_list,
    }




def warn_if_stale(path, label):
    if not os.path.isfile(path):
        return
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            content = fh.read()
    except OSError:
        return
    if not STALE_STORE_RE.search(content):
        return
    print("  ⚠ %s names the RETIRED store (~/.agents/agents.db via the agent-db MCP server)." % label,
          file=sys.stderr)
    print("    The store is ~/.agent-context, served by agent-context. Delete this file and", file=sys.stderr)
    print("    re-run to have a correct one generated — it is untracked and regenerated here.", file=sys.stderr)


def owned_by_us(path):
    if not os.path.isfile(path):
        return False
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            head = "".join(fh.readline() for _ in range(3))
    except OSError:
        return False
    return "generated by agent-context" in head


