def write_manifest(ag, stage):
    'Record what was just projected, so the NEXT run can tell our own output from an edit somebody made.'
    tmp_dir = os.path.join(ag, "tmp")
    try:
        os.makedirs(tmp_dir, exist_ok=True)
    except OSError:
        return
    tmp = os.path.join(tmp_dir, ".materialize-manifest.tmp")
    manifest = os.path.join(tmp_dir, ".materialize-manifest")
    try:
        with open(tmp, "w", encoding="utf-8") as fh:
            for rel in OWNED:
                staged = os.path.join(stage, rel)
                if not os.path.isdir(staged):
                    continue
                for f in walk_files(staged):
                    sub = os.path.relpath(f, staged)
                    fh.write("%s  %s/%s\n" % (sha256_of(f), rel, sub))
    except OSError:
        return
    try:
        os.replace(tmp, manifest)
    except OSError:
        pass




